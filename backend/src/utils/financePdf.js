import PDFDocument from 'pdfkit';

const BRAND = {
  navy: '#1a4a6e',
  ink: '#243447',
  muted: '#5c6f84',
  border: '#dce4ee',
  soft: '#eef3f8',
};

function money(n, currency = 'KES') {
  const v = Number(n || 0);
  return `${currency} ${v.toLocaleString('en-KE', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

function dateStr(v) {
  if (!v) return '—';
  return String(v).slice(0, 10);
}

/**
 * Stream a professional invoice or receipt PDF.
 */
export function streamFinanceDocumentPdf(res, docMeta, company = {}) {
  const isReceipt = docMeta.type === 'RECEIPT';
  const title = isReceipt ? 'PAYMENT RECEIPT' : 'INVOICE';
  const companyName = company.companyName || company['app.name'] || 'RJK REALTY';
  const currency = company.currency || 'KES';

  const filename = `${docMeta.number || title}.pdf`.replace(/[^\w.-]+/g, '_');
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

  const doc = new PDFDocument({ size: 'A4', margin: 48 });
  doc.pipe(res);

  doc.rect(0, 0, doc.page.width, 72).fill(BRAND.navy);
  doc.fillColor('#ffffff').fontSize(18).font('Helvetica-Bold').text(companyName, 48, 28);
  doc.fontSize(10).font('Helvetica').text(title, 48, 50);

  doc.fillColor(BRAND.ink);
  let y = 100;
  doc.fontSize(11).font('Helvetica-Bold').text(isReceipt ? 'Receipt No.' : 'Invoice No.', 48, y);
  doc.font('Helvetica').text(docMeta.number || '—', 160, y);
  doc.font('Helvetica-Bold').text('Date', 340, y);
  doc.font('Helvetica').text(dateStr(docMeta.paymentDate || docMeta.createdAt), 400, y);
  y += 22;

  doc.font('Helvetica-Bold').text('Customer', 48, y);
  doc.font('Helvetica').text(docMeta.customerName || '—', 160, y);
  y += 16;
  if (docMeta.customerPhone) {
    doc.font('Helvetica-Bold').text('Phone', 48, y);
    doc.font('Helvetica').text(docMeta.customerPhone, 160, y);
    y += 16;
  }

  const loc = [
    docMeta.buildingName,
    docMeta.floorName,
    docMeta.unitNumber ? `Unit ${docMeta.unitNumber}` : null,
  ]
    .filter(Boolean)
    .join(' · ');
  if (loc) {
    doc.font('Helvetica-Bold').text('Property', 48, y);
    doc.font('Helvetica').text(loc, 160, y, { width: 360 });
    y += 20;
  }

  y += 8;
  doc.moveTo(48, y).lineTo(547, y).strokeColor(BRAND.border).stroke();
  y += 16;

  doc.font('Helvetica-Bold').text('Description', 48, y);
  y += 16;
  doc.font('Helvetica').fillColor(BRAND.muted).text(docMeta.description || '—', 48, y, { width: 500 });
  y += 36;
  doc.fillColor(BRAND.ink);

  const rows = [
    ['Billing period', docMeta.billingPeriod || '—'],
    ['Previous balance', money(docMeta.previousBalance, currency)],
    ['Current charges', money(docMeta.currentCharges ?? docMeta.amount, currency)],
    ['Amount paid', money(docMeta.amountPaid, currency)],
    ['Remaining balance', money(docMeta.remainingBalance, currency)],
  ];
  if (docMeta.method) rows.push(['Payment method', String(docMeta.methodLabel || docMeta.method)]);
  if (docMeta.reference) rows.push(['Reference', docMeta.reference]);
  if (docMeta.receivedBy) rows.push(['Received by', docMeta.receivedBy]);
  if (docMeta.dueDate) rows.push(['Due date', dateStr(docMeta.dueDate)]);

  for (const [label, value] of rows) {
    doc.font('Helvetica').fillColor(BRAND.muted).text(label, 48, y, { width: 160 });
    doc.fillColor(BRAND.ink).font('Helvetica-Bold').text(String(value), 220, y, { width: 300 });
    y += 18;
  }

  if (docMeta.notes) {
    y += 10;
    doc.font('Helvetica-Bold').text('Notes', 48, y);
    y += 14;
    doc.font('Helvetica').fillColor(BRAND.muted).text(docMeta.notes, 48, y, { width: 500 });
  }

  doc.fillColor(BRAND.muted).fontSize(9).text(
    'Generated by RJK Realty · This document is a formal record of the listed transaction.',
    48,
    doc.page.height - 60,
    { width: 500, align: 'center' },
  );

  doc.end();
}

/**
 * Stream a tenant/customer statement PDF.
 */
export function streamStatementPdf(res, statement, company = {}) {
  const companyName = company.companyName || company['app.name'] || 'RJK REALTY';
  const currency = company.currency || 'KES';
  const filename = `Statement-${(statement.customer?.name || 'customer').replace(/[^\w.-]+/g, '_')}.pdf`;
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

  const doc = new PDFDocument({ size: 'A4', margin: 40, layout: 'landscape' });
  doc.pipe(res);

  doc.rect(0, 0, doc.page.width, 56).fill(BRAND.navy);
  doc.fillColor('#ffffff').fontSize(16).font('Helvetica-Bold').text(companyName, 40, 18);
  doc.fontSize(10).font('Helvetica').text('CUSTOMER STATEMENT', 40, 38);

  let y = 72;
  doc.fillColor(BRAND.ink).fontSize(11).font('Helvetica-Bold').text(statement.customer?.name || '—', 40, y);
  y += 14;
  doc.font('Helvetica').fontSize(9).fillColor(BRAND.muted);
  const loc = [
    statement.unit?.building?.name,
    statement.unit?.floor?.name,
    statement.unit?.roomNumber ? `Unit ${statement.unit.roomNumber}` : null,
  ]
    .filter(Boolean)
    .join(' · ');
  doc.text([statement.customer?.phone, loc].filter(Boolean).join('  |  '), 40, y);
  y += 18;

  const cols = [
    { x: 40, w: 70, h: 'Date' },
    { x: 110, w: 260, h: 'Description' },
    { x: 370, w: 80, h: 'Debit' },
    { x: 450, w: 80, h: 'Credit' },
    { x: 530, w: 90, h: 'Balance' },
    { x: 620, w: 110, h: 'Method / Ref' },
  ];
  doc.rect(40, y, doc.page.width - 80, 18).fill(BRAND.soft);
  doc.fillColor(BRAND.ink).font('Helvetica-Bold').fontSize(8);
  for (const c of cols) doc.text(c.h, c.x, y + 5, { width: c.w });
  y += 22;

  doc.font('Helvetica').fontSize(8);
  for (const line of statement.lines || []) {
    if (y > doc.page.height - 60) {
      doc.addPage();
      y = 40;
    }
    doc.fillColor(BRAND.ink).text(dateStr(line.date), cols[0].x, y, { width: cols[0].w });
    doc.text(line.description || '', cols[1].x, y, { width: cols[1].w });
    doc.text(line.debit ? money(line.debit, currency) : '—', cols[2].x, y, { width: cols[2].w });
    doc.text(line.credit ? money(line.credit, currency) : '—', cols[3].x, y, { width: cols[3].w });
    doc.text(money(line.balance, currency), cols[4].x, y, { width: cols[4].w });
    doc.fillColor(BRAND.muted).text(
      [line.method, line.reference].filter(Boolean).join(' / ') || '—',
      cols[5].x,
      y,
      { width: cols[5].w },
    );
    y += 14;
  }

  y += 10;
  doc.fillColor(BRAND.ink).font('Helvetica-Bold').fontSize(10);
  doc.text(`Outstanding balance: ${money(statement.summary?.outstandingBalance, currency)}`, 40, y);
  y += 14;
  doc.font('Helvetica').fillColor(BRAND.muted);
  doc.text(`Deposits held (liability): ${money(statement.summary?.depositsHeld, currency)}`, 40, y);

  doc.end();
}
